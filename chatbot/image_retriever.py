# Catalog cache
_IMAGE_DB_CACHE: Optional[Dict[str, Any]] = None
DB_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'data', 'image_database.json')

def load_image_database() -> Dict[str, Any]:
    """Loads and caches the verified image database JSON."""
    global _IMAGE_DB_CACHE
    if _IMAGE_DB_CACHE is not None:
        return _IMAGE_DB_CACHE

    if os.path.exists(DB_PATH):
        try:
            with open(DB_PATH, 'r', encoding='utf-8') as f:
                _IMAGE_DB_CACHE = json.load(f)
                return _IMAGE_DB_CACHE
        except Exception as e:
            print(f"[ImageRetriever Error] Failed to load image_database.json: {e}")
            
    _IMAGE_DB_CACHE = {"components": {}, "vehicles": {}}
    return _IMAGE_DB_CACHE

def sanitize_ai_text(text: str) -> str:
    """
    CRITICAL DOMAIN RULE: The AI should not be allowed to invent image URLs.
    Strips out any hallucinated markdown image tags or suspicious image URLs
    from the AI text so only verified catalog assets can be displayed.
    """
    if not text:
        return ""
    # Strip markdown images: ![alt](url)
    sanitized = re.sub(r'!\[.*?\]\(https?://[^\s)]+\)', '', text)
    # Strip raw image URLs ending with common extensions if generated by AI
    sanitized = re.sub(r'https?://[^\s]+\.(?:jpg|jpeg|png|webp|gif|svg)(?:\?[^\s]*)?', '', sanitized, flags=re.IGNORECASE)
    # Clean redundant blank lines created by stripping
    sanitized = re.sub(r'\n{3,}', '\n\n', sanitized).strip()
    return sanitized

def _match_keywords(text: str, keywords: List[str]) -> int:
    """
    Returns match score based on keyword presence in text.
    Accurately supports both Latin word boundaries and Unicode/Tamil scripts.
    """
    text_lower = text.lower()
    score = 0
    for kw in keywords:
        kw_lower = kw.lower().strip()
        if not kw_lower:
            continue
            
        # Check if keyword is pure ASCII / Latin
        is_ascii = all(ord(c) < 128 for c in kw_lower)
        if is_ascii and ' ' not in kw_lower:
            # Word boundary pattern for single English words
            pattern = r'(?:\b|_)' + re.escape(kw_lower) + r'(?:\b|_)'
            if re.search(pattern, text_lower):
                score += max(len(kw_lower), 5)
        else:
            # Phrase match or Unicode / Indic script match (e.g. Tamil)
            if kw_lower in text_lower:
                score += max(len(kw_lower) * 2, 8)
    return score

def detect_vehicle_type(query_text: str = "", default_type: Optional[str] = None) -> str:
    """
    Identifies whether the user is querying for a bike or a car.
    Prioritizes explicit keywords in user message over the session default.
    """
    text = (query_text or "").lower()
    
    bike_keywords = [
        "bike", "motorcycle", "scooter", "scooty", "two wheeler", "2 wheeler",
        "superbike", "cruiser", "moped", "பைக்", "இருசக்கர"
    ]
    car_keywords = [
        "car", "automobile", "sedan", "suv", "hatchback", "four wheeler", "4 wheeler",
        "coupe", "convertible", "motorsport car", "கார்", "மகிழுந்து"
    ]
    
    has_bike = any(re.search(r'\b' + re.escape(w) + r'\b', text) for w in bike_keywords) or any(w in text for w in ["பைக்", "இருசக்கர"])
    has_car = any(re.search(r'\b' + re.escape(w) + r'\b', text) for w in car_keywords) or any(w in text for w in ["கார்", "மகிழுந்து"])
    
    if has_bike and not has_car:
        return "bike"
    elif has_car and not has_bike:
        return "car"
    elif default_type in ["bike", "car"]:
        return default_type
    return "bike"

def detect_brand(query_text: str = "") -> Optional[str]:
    """Extracts vehicle brand from query if present."""
    text = (query_text or "").lower()
    known_brands = [
        "yamaha", "royal enfield", "enfield", "ktm", "honda", "suzuki", "kawasaki", 
        "ducati", "bmw", "tata", "maruti", "hyundai", "toyota", "mahindra", 
        "bajaj", "tvs", "hero", "audi", "mercedes", "porsche"
    ]
    for b in known_brands:
        if re.search(r'\b' + re.escape(b) + r'\b', text):
            return b
    return None

def validate_image_metadata(item: Optional[Dict[str, Any]], expected_vehicle_type: str) -> Tuple[bool, str]:
    """
    CRITICAL RULE: The image MUST belong to the requested vehicle type (e.g. bike, not a car).
    Never show a car image when a bike was requested, or vice versa.
    """
    if not item or not isinstance(item, dict):
        return False, "No item provided for validation."

    item_vehicle_type = item.get("vehicle_type", "both").lower()
    expected = (expected_vehicle_type or "").lower()

    if item.get("type") == "vehicle":
        # Vehicle must strictly match or be "both"
        if item_vehicle_type != expected and item_vehicle_type != "both":
            return False, f"Type mismatch: Image belongs to {item_vehicle_type}, but {expected} was requested."

    elif item.get("type") == "component":
        # Components typically apply to both, but check if specifically restricted
        if item_vehicle_type not in [expected, "both"]:
            return False, f"Component is restricted to {item_vehicle_type}, not {expected}."

    return True, "Validation passed."

def match_vehicle_or_component(
    query_text: str = "",
    structured_data: Optional[Dict[str, Any]] = None,
    vehicle_type: Optional[str] = None
) -> Tuple[Optional[Dict[str, Any]], str]:
    """
    Deterministically identifies vehicle or component and retrieves the matching verified image.
    STRICTLY respects expected vehicle type (Bike vs Car).
    Returns: (matched_item_dict_or_None, item_type: 'vehicle'|'component'|'none')
    """
    db = load_image_database()
    components = db.get("components", {})
    vehicles = db.get("vehicles", {})

    expected_type = detect_vehicle_type(query_text, default_type=vehicle_type)
    combined_text = f"{query_text or ''} "
    
    # Check vision detection first if available (exact match guarantee)
    if structured_data and isinstance(structured_data, dict):
        vision = structured_data.get("vision_detection") or {}
        part_class = vision.get("part_class", "").lower().replace("-", "_")
        if part_class in components:
            return components[part_class], "component"
            
        # Check structured title or components
        title = structured_data.get("title", "")
        combined_text += f"{title} "
        for c in structured_data.get("components", []):
            combined_text += f"{c.get('name', '')} {c.get('category', '')} "

    # 1. Match Vehicles (STRICT TYPE ENFORCEMENT: Ignore vehicles of the wrong type!)
    best_vehicle = None
    best_v_score = 0
    for v_id, v_data in vehicles.items():
        v_type = v_data.get("vehicle_type", "both")
        # STRICT RULE: A car image must NEVER be matched if expected_type is bike
        if v_type != expected_type and v_type != "both":
            continue

        score = _match_keywords(combined_text, v_data.get("keywords", []))
        if score > best_v_score and score >= 4:
            best_v_score = score
            best_vehicle = v_data

    # 2. Match Components
    best_component = None
    best_c_score = 0
    for c_id, c_data in components.items():
        c_type = c_data.get("vehicle_type", "both")
        if c_type != expected_type and c_type != "both":
            continue

        score = _match_keywords(combined_text, c_data.get("keywords", []))
        if score > best_c_score and score >= 4:
            best_c_score = score
            best_component = c_data

    # Priority decision:
    # If the user specifically asked about a vehicle model, return vehicle
    # If the user asked about a part (or troubleshooting), return component
    if best_vehicle and best_v_score > (best_c_score * 1.2):
        return best_vehicle, "vehicle"
    elif best_component:
        return best_component, "component"
    elif best_vehicle:
        return best_vehicle, "vehicle"

    return None, "none"

_LIVE_SEARCH_CACHE: Dict[str, Any] = {}

def live_image_search_fallback(query: str, expected_type: str = "bike") -> Optional[Dict[str, Any]]:
    """
    Backend live image search fallback provider.
    Activated if ENABLE_LIVE_IMAGE_SEARCH=true and local match is absent.
    Uses Wikimedia Commons & Wikipedia safe search without hallucination.
    """
    enable_live = os.environ.get("ENABLE_LIVE_IMAGE_SEARCH", "true").lower() in ("true", "1", "yes")
    if not enable_live or not query:
        return None

    # Clean query: strip non-alphanumeric except spaces
    clean_query = re.sub(r'[^a-zA-Z0-9\s]', '', query).strip()
    # Remove common image filler words
    clean_query = re.sub(r'\b(show|me|a|an|the|image|photo|picture|pic|specs|car|bike|motorcycle|vehicle)\b', '', clean_query, flags=re.I).strip()
    if not clean_query:
        return None

    cache_key = f"{expected_type}:{clean_query.lower()}"
    if cache_key in _LIVE_SEARCH_CACHE:
        return _LIVE_SEARCH_CACHE[cache_key]

    try:
        import urllib.request
        import urllib.parse
        import json
        import ssl

        # Create unverified SSL context to prevent Windows handshake timeouts
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE

        # Brand-level cross-type rejection: Brands primarily known for cars must not return live assets for generic bike queries
        car_predominant_brands = {"bmw", "audi", "mercedes", "porsche", "ferrari", "lamborghini", "tata", "hyundai", "maruti", "toyota", "ford", "volkswagen"}
        bike_predominant_brands = {"yamaha", "royal enfield", "ducati", "ktm", "kawasaki", "harley", "tvs", "hero", "bajaj"}

        clean_lower = clean_query.lower().strip()
        if expected_type == "bike" and clean_lower in car_predominant_brands:
            # e.g. "BMW bike", "Audi bike", "Tata bike" -> Must show strict placeholder
            return None
        if expected_type == "car" and clean_lower in bike_predominant_brands:
            # e.g. "Yamaha car", "Ducati car", "KTM car" -> Must show strict placeholder
            return None

        # Build targeted search query
        search_query = clean_query
        if expected_type == "bike" and not any(k in clean_lower for k in ("motorcycle", "bike", "scooter")):
            search_query = f"{clean_query} motorcycle"
        elif expected_type == "car" and not any(k in clean_lower for k in ("car", "automobile", "suv", "sedan")):
            search_query = f"{clean_query} car"

        # Wikipedia / Wikimedia prefix search query
        url = (
            "https://en.wikipedia.org/w/api.php?action=query&format=json"
            f"&generator=prefixsearch&gpssearch={urllib.parse.quote(search_query)}"
            "&gpslimit=3&prop=pageimages&piprop=thumbnail&pithumbsize=960"
        )
        req = urllib.request.Request(url, headers={
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AIMoto/1.0 (Automotive Education)'
        })

        resp_data = None
        for attempt in range(2):
            try:
                with urllib.request.urlopen(req, timeout=6, context=ctx) as resp:
                    resp_data = json.loads(resp.read().decode('utf-8'))
                    break
            except Exception as retry_err:
                if attempt == 1:
                    raise retry_err

        if resp_data:
            pages = resp_data.get('query', {}).get('pages', {})
            
            # Car vs bike anti-confusion filter
            car_anti_terms = {"sedan", "hatchback", "suv", "truck", "coupe", "convertible", "wagon", "minivan", "group", "ag", "motors", "company"}
            bike_anti_terms = {"motorcycle", "scooter", "superbike", "moped", "dirt bike"}
            non_photo_terms = {"logo", "emblem", "badge", "icon", "symbol", "diagram", "flag", "sign", "map", ".svg"}

            for pid, p in pages.items():
                thumb = p.get('thumbnail')
                title = p.get('title', clean_query)
                title_low = title.lower()
                
                # Cross-type strict isolation
                if expected_type == "bike" and any(cat in title_low for cat in car_anti_terms):
                    continue
                if expected_type == "car" and any(bat in title_low for bat in bike_anti_terms):
                    continue

                if thumb and 'source' in thumb:
                    img_url = thumb['source']
                    # Skip logos, emblems, SVGs
                    if any(npt in img_url.lower() or npt in title_low for npt in non_photo_terms):
                        continue

                    if any(img_url.lower().endswith(ext) or ext in img_url.lower() for ext in ('.jpg', '.jpeg', '.png', '.webp')):
                        res_obj = {
                            "name": title,
                            "type": "live_search",
                            "vehicle_type": expected_type,
                            "image_url": img_url,
                            "is_live_search": True,
                            "is_verified_image": False,
                            "confidence": 75,
                            "match_status": "live_fallback",
                            "safety_guidance": "Live reference image provided from Wikimedia Commons. Verify vehicle model specifications with certified manufacturer service manuals."
                        }
                        _LIVE_SEARCH_CACHE[cache_key] = res_obj
                        return res_obj
    except Exception as e:
        print(f"[LiveSearchProvider Info] Fallback search omitted: {e}")

    return None

def enrich_structured_card(
    structured_data: Optional[Any] = None,
    query_text: str = "",
    vehicle_type: Optional[str] = None,
    vehicle_context: Optional[str] = None
) -> Optional[Dict[str, Any]]:
    """
    Attaches verified local image assets, specifications, price estimates,
    and safety guidance to the structured card payload.
    
    Enforces Phase 2 exact model & component matching:
    - Queries the VehicleKnowledge SQLite database first.
    - Strictly rejects similar or unverified models.
    - Flags year range mismatches.
    - If unconfirmed or mismatched, returns a dedicated visual placeholder
      explaining why the image is unavailable instead of displaying another vehicle.
    """
    if isinstance(structured_data, str) and (isinstance(query_text, dict) or query_text is None or query_text == ""):
        query_text, structured_data = structured_data, query_text
        if not isinstance(structured_data, dict):
            structured_data = None

    if vehicle_type is None and vehicle_context is not None:
        vehicle_type = vehicle_context
    from chatbot.knowledge_matcher import match_exact_vehicle_knowledge

    expected_type = detect_vehicle_type(query_text, default_type=vehicle_type)
    detected_b = detect_brand(query_text)
    is_image_request = any(w in (query_text or "").lower() for w in ["image", "photo", "picture", "show", "look like", "படம்", "காட்டு"])

    # First, run Phase 2 Exact Knowledge Matcher
    exact_res = None
    try:
        exact_res = match_exact_vehicle_knowledge(query_text, vehicle_type=expected_type)
    except Exception as e:
        print(f"[KnowledgeMatcher Info] Exact lookup deferred: {e}")

    # Handle explicit rejections from Exact Matcher (Similar model, year mismatch, unknown model/brand)
    if exact_res and exact_res.get("status") in ["unknown_manufacturer", "unknown_model", "wrong_vehicle_type", "year_mismatch", "unknown_component"]:
        # If manufacturer or model is uncataloged and user explicitly requested an image, attempt safe live fallback
        if exact_res.get("status") in ["unknown_manufacturer", "unknown_model"] and is_image_request:
            live_res = live_image_search_fallback(query_text, expected_type=expected_type)
            if live_res:
                return {
                    "response_type": "vehicle_info",
                    "title": live_res.get("name"),
                    "category": f"Live Visual Reference ({expected_type.capitalize()})",
                    "vehicle_type": expected_type,
                    "target_vehicle_type": expected_type,
                    "image_vehicle_type": expected_type,
                    "image_url": live_res.get("image_url"),
                    "is_verified_image": False,
                    "is_live_search": True,
                    "is_placeholder": False,
                    "confidence": 75,
                    "match_status": "live_fallback",
                    "safety_warning": live_res.get("safety_guidance"),
                    "summary": f"Live automotive reference for {live_res.get('name')} retrieved via Wikimedia Commons."
                }

        title_text = exact_res.get("placeholder_title") or f"Verified {expected_type.capitalize()} Information"
        placeholder_payload = {
            "response_type": "placeholder_info",
            "title": title_text,
            "vehicle_type": expected_type,
            "target_vehicle_type": expected_type,
            "manufacturer": exact_res.get("manufacturer"),
            "model": exact_res.get("model"),
            "confidence": 0.0,
            "match_status": exact_res.get("status"),
            "is_placeholder": True,
            "placeholder_type": expected_type,
            "placeholder_title": exact_res.get("placeholder_title"),
            "placeholder_message": exact_res.get("placeholder_message"),
            "safety_warning": "Strict vehicle type and model validation active. Unverified or similar models are never substituted."
        }
        if structured_data and isinstance(structured_data, dict):
            structured_data.update(placeholder_payload)
            structured_data.pop("image_url", None)
            return structured_data
        return placeholder_payload

    # Handle Exact Match found in Phase 2 database
    if exact_res and exact_res.get("status") == "exact_match":
        specs_list = []
        if exact_res.get("specifications"):
            specs_list = [{"label": k, "value": str(v)} for k, v in exact_res["specifications"].items()]
            
        card_title = exact_res.get("model")
        if exact_res.get("component_name"):
            card_title = f"{exact_res.get('model')} - {exact_res.get('component_name')}"
        if exact_res.get("manufacturer") and exact_res.get("manufacturer") not in card_title:
            card_title = f"{exact_res.get('manufacturer')} {card_title}"

        raw_conf = exact_res.get("confidence", 1.0)
        conf_pct = int(raw_conf * 100) if raw_conf <= 1.0 else int(raw_conf)

        exact_payload = {
            "response_type": "vehicle_info" if not exact_res.get("component_name") else "component_info",
            "title": card_title,
            "manufacturer": exact_res.get("manufacturer"),
            "model": exact_res.get("model"),
            "component_name": exact_res.get("component_name"),
            "vehicle_type": expected_type,
            "target_vehicle_type": expected_type,
            "image_vehicle_type": expected_type,
            "confidence": conf_pct,
            "match_status": "exact_match",
            "specifications": specs_list,
            "image_url": exact_res.get("image_path"),
            "is_verified_image": bool(exact_res.get("image_path")),
            "is_placeholder": exact_res.get("is_placeholder", False),
            "placeholder_type": expected_type if exact_res.get("is_placeholder") else None,
            "placeholder_title": exact_res.get("placeholder_title"),
            "placeholder_message": exact_res.get("placeholder_message")
        }

        if not structured_data or not isinstance(structured_data, dict):
            return exact_payload

        # Merge into existing AI structured card
        structured_data.update(exact_payload)
        return structured_data

    # Fallback to general catalog matching if exact model was not in Phase 2 DB
    if not structured_data or not isinstance(structured_data, dict):
        matched, match_type = match_vehicle_or_component(query_text, None, expected_type)
        if matched:
            valid, _ = validate_image_metadata(matched, expected_type)
            if valid:
                return {
                    "response_type": f"{match_type}_info",
                    "title": matched.get("name"),
                    "category": matched.get("category"),
                    "vehicle_type": expected_type,
                    "target_vehicle_type": expected_type,
                    "image_vehicle_type": matched.get("vehicle_type"),
                    "image_url": matched.get("image_url"),
                    "is_verified_image": matched.get("verified", True),
                    "is_placeholder": False,
                    "confidence": 0.9,
                    "match_status": "catalog_match",
                    "price_estimate": matched.get("price_estimate"),
                    "specifications": [
                        {"label": k, "value": str(v)} for k, v in matched.get("specifications", {}).items()
                    ] if isinstance(matched.get("specifications"), dict) else matched.get("specifications"),
                    "safety_warning": matched.get("safety_guidance"),
                    "diagnostic_info": matched.get("diagnostic_info")
                }

        # If user asked for an image and no verified image of the expected vehicle type exists:
        if is_image_request:
            live_res = live_image_search_fallback(query_text, expected_type=expected_type)
            if live_res:
                return {
                    "response_type": "vehicle_info",
                    "title": live_res.get("name"),
                    "category": f"Live Visual Reference ({expected_type.capitalize()})",
                    "vehicle_type": expected_type,
                    "target_vehicle_type": expected_type,
                    "image_vehicle_type": expected_type,
                    "image_url": live_res.get("image_url"),
                    "is_verified_image": False,
                    "is_live_search": True,
                    "is_placeholder": False,
                    "confidence": 75,
                    "match_status": "live_fallback",
                    "safety_warning": live_res.get("safety_guidance"),
                    "summary": f"Live automotive reference for {live_res.get('name')} retrieved via Wikimedia Commons."
                }
            brand_label = f"{detected_b.title()} " if detected_b else ""
            return {
                "response_type": "placeholder_info",
                "title": f"Verified {brand_label}{expected_type.capitalize()} Image",
                "vehicle_type": expected_type,
                "is_placeholder": True,
                "confidence": 0.0,
                "match_status": "unverified",
                "placeholder_type": expected_type,
                "placeholder_title": f"Verified {brand_label}{expected_type.capitalize()} Image Unavailable",
                "placeholder_message": f"Our local verified database does not currently have an approved image for {brand_label}{expected_type}. Strict validation prevents displaying an unrelated vehicle.",
                "safety_warning": "Strict vehicle type validation enforced to prevent showing unrelated images."
            }
        return structured_data

    # Annotate card with expected vehicle type
    structured_data["vehicle_type"] = expected_type
    structured_data["target_vehicle_type"] = expected_type

    # 1. Match primary vehicle or component for the overall card
    matched, match_type = match_vehicle_or_component(query_text, structured_data, expected_type)
    
    # If no local match, check live search fallback
    if not matched:
        matched = live_image_search_fallback(query_text, expected_type=expected_type)
        if matched:
            match_type = "live_search"

    if matched:
        # Validate metadata strictly
        is_valid, reason = validate_image_metadata(matched, expected_type)
        if is_valid:
            structured_data["image_url"] = matched.get("image_url")
            structured_data["image_name"] = matched.get("name")
            structured_data["image_type"] = match_type
            structured_data["image_vehicle_type"] = matched.get("vehicle_type")
            structured_data["is_verified_image"] = matched.get("verified", True)
            structured_data["is_placeholder"] = False
            structured_data["confidence"] = 0.9
            structured_data["match_status"] = "catalog_match"
        else:
            print(f"[Validation Blocked] {reason}")
            structured_data.pop("image_url", None)
            if is_image_request or structured_data.get("response_type") == "vehicle_info":
                structured_data["is_placeholder"] = True
                structured_data["placeholder_type"] = expected_type
                structured_data["placeholder_title"] = f"Verified {expected_type.capitalize()} Image Unavailable"
                structured_data["placeholder_message"] = reason

        # Inject price estimate if not present
        if not structured_data.get("price_estimate") and matched.get("price_estimate"):
            structured_data["price_estimate"] = matched.get("price_estimate")

        # Inject or reinforce safety warning if missing
        if not structured_data.get("safety_warning") and matched.get("safety_guidance"):
            structured_data["safety_warning"] = matched.get("safety_guidance")

        # Inject diagnostic checks if it's a diagnostic result and missing details
        if matched.get("diagnostic_info"):
            d_info = matched["diagnostic_info"]
            if not structured_data.get("possible_causes") and d_info.get("symptoms"):
                structured_data["possible_causes"] = d_info["symptoms"]
            if not structured_data.get("recommended_checks") and d_info.get("checks"):
                structured_data["recommended_checks"] = d_info["checks"]
    elif is_image_request or structured_data.get("response_type") == "vehicle_info":
        # Unconfirmed vehicle image -> Provide placeholder instead of leaving ambiguous or showing wrong vehicle
        brand_label = f"{detected_b.title()} " if detected_b else ""
        structured_data["is_placeholder"] = True
        structured_data["placeholder_type"] = expected_type
        structured_data["placeholder_title"] = f"Verified {brand_label}{expected_type.capitalize()} Image Unavailable"
        structured_data["placeholder_message"] = f"No verified image for {brand_label}{expected_type} is present in the local catalog. Unrelated images are strictly suppressed."

    # 2. Enrich individual components in `components` list if present
    db = load_image_database()
    comp_db = db.get("components", {})
    if "components" in structured_data and isinstance(structured_data["components"], list):
        for comp in structured_data["components"]:
            comp_name = (comp.get("name") or "").lower()
            matched_comp = None
            for c_id, c_data in comp_db.items():
                if _match_keywords(comp_name, c_data.get("keywords", [])) >= 4:
                    # Validate component against expected vehicle type
                    val, _ = validate_image_metadata(c_data, expected_type)
                    if val:
                        matched_comp = c_data
                    break
            
            if matched_comp:
                comp["image_url"] = matched_comp.get("image_url")
                comp["vehicle_type"] = matched_comp.get("vehicle_type")
                if not comp.get("price_estimate"):
                    comp["price_estimate"] = matched_comp.get("price_estimate")
                if not comp.get("safety_warning") and matched_comp.get("safety_guidance"):
                    comp["safety_warning"] = matched_comp.get("safety_guidance")

    return structured_data
